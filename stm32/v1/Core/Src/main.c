#define ADC3_CH_COUNT 4
volatile uint8_t ADC3Data[ADC3_CH_COUNT] = {0x11, 0x12, 0x13, 0x14};

void SPI1_IRQHandler(void)
{
  // Dumb read to avoid repeated interrupt (may be replaced with
  volatile uint8_t tmp = hspi1.Instance->DR;

  if(SpiHead == SpiTail) {
    // No data to send
    hspi1.Instance->DR = 0;
  } else {
    hspi1.Instance->DR = SpiBuffer[SpiTail++];
    SpiTail &= 0xFFFF;
  }
}

